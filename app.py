"""
app.py - Streamlit web interface for FodderMind AI.

Provides:
- Interactive Farm Input Configuration Form (Goat Pen, Hydroponic Rack, Field Plot)
- Traceable Feed Library Table with CSV import/export and validation
- Deterministic Simulation Engine execution (Rule-Based vs Constrained LP Optimizer)
- Results, trajectory time-series charts, and physiological safety audits
"""

from __future__ import annotations

import os
import streamlit as st
import pandas as pd
import numpy as np

from models.schemas import (
    FarmResources,
    FeedItem,
    GoatPenProfile,
    SimulationConfig,
    SimulationResult,
    load_feed_library_from_csv,
    validate_feed_library_df,
)
from simulation.farm_simulator import FarmSimulator
from algorithms.rule_based import RuleBasedAgronomistPolicy
from algorithms.ration_lp import LeastCostRationOptimizer
from reports.generator import generate_summary_markdown, compare_simulation_results

# Set page configuration
st.set_page_config(
    page_title="FodderMind AI — Simulation-First Decision Twin",
    page_icon="🐐",
    layout="wide",
    initial_sidebar_state="expanded",
)

# Custom Styling
st.markdown(
    """
    <style>
    .metric-card {
        background-color: #f8f9fa;
        border-radius: 8px;
        padding: 12px;
        border-left: 5px solid #28a745;
    }
    .disclaimer-box {
        background-color: #fff3cd;
        color: #856404;
        padding: 10px;
        border-radius: 5px;
        border-left: 4px solid #ffeeba;
        font-size: 0.9em;
    }
    </style>
    """,
    unsafe_allow_html=True,
)

# Application Header
st.title("🐐 FodderMind AI")
st.markdown(
    "**Simulation-First Fodder & Goat-Growth Optimization System**  \n"
    "*Designed for School Scientific Innovation Competitions (SFIC / ISEF Standard)*"
)

st.markdown(
    """
    <div class="disclaimer-box">
    <strong>Scientific Transparency Notice:</strong> Trajectories generated by this software are synthetic 
    and derived from deterministic mathematical formulations (NRC 2007 small ruminant energetics, mass-balance 
    agronomy, and FIFO spoilage dynamics). Biological constants are configurable research placeholders. 
    Do not deploy for commercial livestock feeding without qualified veterinary review.
    </div>
    """,
    unsafe_allow_html=True,
)

st.write("")

# Sidebar: Farm Parameters Form
st.sidebar.header("🛠️ Farm Configuration")

with st.sidebar.form("farm_config_form"):
    st.subheader("1. Livestock Pen Cohort")
    head_count = st.number_input("Pen Head Count (Goats)", min_value=1, max_value=50, value=5, step=1)
    initial_weight = st.number_input("Initial Mean Body Weight (kg)", min_value=10.0, max_value=60.0, value=20.0, step=0.5)
    target_adg = st.number_input("Target ADG per Head (g/day)", min_value=20.0, max_value=250.0, value=100.0, step=10.0)

    st.subheader("2. Dual Fodder Infrastructure")
    hydro_trays = st.number_input("Hydroponic Trays (Total Rack)", min_value=0, max_value=120, value=28, step=7)
    seed_per_tray = st.number_input("Seed per Tray (kg)", min_value=0.5, max_value=5.0, value=1.5, step=0.1)
    seed_cost_kg = st.number_input("Seed Cost (INR/kg)", min_value=5.0, max_value=100.0, value=22.0, step=1.0)
    
    field_area = st.number_input("Field Napier Area (m²)", min_value=0.0, max_value=5000.0, value=500.0, step=50.0)
    field_interval = st.number_input("Field Cutting Interval (days)", min_value=15, max_value=60, value=30, step=5)

    st.subheader("3. Financials & Resources")
    initial_cash = st.number_input("Initial Cash Balance (INR)", min_value=0.0, max_value=500000.0, value=15000.0, step=1000.0)
    water_cost = st.number_input("Water Cost (INR / Liter)", min_value=0.00, max_value=1.00, value=0.03, step=0.01)
    meat_price = st.number_input("Goat Meat Price (INR / kg live)", min_value=100.0, max_value=800.0, value=350.0, step=25.0)

    st.subheader("4. Experiment Controls")
    horizon_days = st.slider("Planning Horizon (Days)", min_value=10, max_value=90, value=30, step=5)
    random_seed = st.number_input("Random Seed", min_value=0, max_value=99999, value=42, step=1)

    submitted = st.form_submit_button("Update Configuration")

# Instantiate configuration objects
config = SimulationConfig(horizon_days=int(horizon_days), random_seed=int(random_seed))
pen_profile = GoatPenProfile(
    head_count=int(head_count),
    initial_mean_weight_kg=float(initial_weight),
    target_adg_g_day=float(target_adg),
)
resources = FarmResources(
    hydroponic_trays_total=int(hydro_trays),
    hydroponic_seed_per_tray_kg=float(seed_per_tray),
    hydroponic_seed_cost_kg=float(seed_cost_kg),
    field_fodder_area_sqm=float(field_area),
    field_cutting_interval_days=int(field_interval),
    initial_cash_reserve=float(initial_cash),
    water_cost_per_l=float(water_cost),
    goat_meat_price_per_kg_live=float(meat_price),
)

# Load baseline feed library
feed_csv_path = os.path.join("data", "feed_library.csv")
if os.path.exists(feed_csv_path):
    default_feed_lib = load_feed_library_from_csv(feed_csv_path)
else:
    st.error("Default feed library not found in data/feed_library.csv.")
    st.stop()

# Main Application Tabs
tab_catalog, tab_sim, tab_benchmark, tab_audit = st.tabs([
    "📋 1. Sourced Feed Library",
    "🚀 2. Farm Simulation",
    "⚖️ 3. Policy Benchmark",
    "📄 4. Audit & Scientific Export",
])

with tab_catalog:
    st.header("Sourced Nutritional Ingredients Catalog")
    st.markdown(
        "Every feed item specifies its Dry Matter basis, crude protein, metabolizable energy, "
        "and literature provenance (e.g. FAO Feedipedia, ICAR small ruminants)."
    )

    feed_rows = []
    for f in default_feed_lib.values():
        feed_rows.append({
            "Name": f.name,
            "Category": f.category,
            "DM %": f.dry_matter_pct,
            "CP (% DM)": f.crude_protein_pct_dm,
            "ME (MJ/kg DM)": f.metabolizable_energy_mj_kg_dm,
            "NDF (% DM)": f.ndf_pct_dm,
            "Cost/kg As-Fed": f.unit_cost_as_fed,
            "Cost/kg DM": round(f.cost_per_kg_dm, 2),
            "Provenance": f.provenance_source,
            "Evidence": f.evidence_status,
        })
    feed_df = pd.DataFrame(feed_rows)
    st.dataframe(feed_df, use_container_width=True)

    st.subheader("Upload Custom Feed Catalog (CSV)")
    uploaded_file = st.file_uploader("Upload CSV formatted feed library", type=["csv"])
    active_feed_lib = default_feed_lib

    if uploaded_file is not None:
        try:
            custom_df = pd.read_csv(uploaded_file)
            is_valid, validation_errors = validate_feed_library_df(custom_df)
            if is_valid:
                st.success("Uploaded CSV passed all schema and physiological range validation checks!")
                # Parse into dictionary
                temp_dict = {}
                for _, r in custom_df.iterrows():
                    item = FeedItem(
                        name=str(r["name"]),
                        category=str(r["category"]),
                        dry_matter_pct=float(r["dry_matter_pct"]),
                        crude_protein_pct_dm=float(r["crude_protein_pct_dm"]),
                        metabolizable_energy_mj_kg_dm=float(r["metabolizable_energy_mj_kg_dm"]),
                        ndf_pct_dm=float(r["ndf_pct_dm"]),
                        unit_cost_as_fed=float(r["unit_cost_as_fed"]),
                        provenance_source=str(r.get("provenance_source", "Uploaded CSV")),
                        evidence_status="user_provided",
                    )
                    temp_dict[item.name] = item
                active_feed_lib = temp_dict
                st.dataframe(custom_df, use_container_width=True)
            else:
                st.error("Uploaded CSV failed schema validation:")
                for err in validation_errors:
                    st.write(f"- {err}")
        except Exception as e:
            st.error(f"Error reading uploaded CSV: {e}")

with tab_sim:
    st.header("Simulation Execution & Trajectory Dynamics")
    col_strat, col_btn = st.columns([3, 1])

    with col_strat:
        strategy = st.radio(
            "Select Farm Decision Policy:",
            options=["Rule-Based Heuristic (Extension Baseline)", "Constrained Linear Program (SciPy linprog)"],
            horizontal=True,
        )

    with col_btn:
        st.write("")
        run_clicked = st.button("▶ Run Simulation", use_container_width=True, type="primary")

    if run_clicked:
        sim = FarmSimulator(config, pen_profile, resources, active_feed_lib)
        if "Rule-Based" in strategy:
            policy = RuleBasedAgronomistPolicy()
            policy_label = "Rule_Based"
        else:
            policy = LeastCostRationOptimizer(target_adg_g_head=float(target_adg))
            policy_label = "Constrained_LP"

        with st.spinner("Simulating daily biological transitions & inventory flows..."):
            result = sim.run_simulation(policy)
            st.session_state["last_sim_result"] = result
            st.session_state["last_policy_label"] = policy_label

    if "last_sim_result" in st.session_state:
        res = st.session_state["last_sim_result"]
        df_traj = res.trajectory_df

        st.subheader(f"Simulation Diagnostics: {st.session_state.get('last_policy_label', '')}")

        # Top Metric Cards
        m1, m2, m3, m4, m5 = st.columns(5)
        m1.metric("Final Pen Weight", f"{res.final_pen_weight_kg:.1f} kg", f"+{res.total_pen_weight_gain_kg:.1f} kg")
        m2.metric("Mean ADG", f"{df_traj['daily_adg_g_head'].mean():.1f} g/d")
        m3.metric("Total Feed Cost", f"INR {res.total_feed_cost:.2f}")
        m4.metric("Gross MOFC", f"INR {res.gross_margin_over_feed_cost:.2f}")
        m5.metric("Spoilage Loss", f"{res.total_spoilage_loss_kg_dm:.1f} kg DM")

        # Physiological Safety Banners
        if res.acidosis_risk_days > 0 or res.energy_deficit_days > 0:
            st.warning(
                f"⚠️ Physiological Audit Flags: {res.acidosis_risk_days} days below minimum fiber threshold (Acidosis risk); "
                f"{res.energy_deficit_days} days in negative energy balance (Weight loss)."
            )
        else:
            st.success("✅ Physiological Audit Passed: Zero acidosis or severe starvation days detected.")

        # Interactive Charts
        st.subheader("Live Telemetry Charts")
        c1, c2 = st.columns(2)

        with c1:
            st.markdown("**Pen Aggregate Live Weight Trajectory (kg)**")
            st.line_chart(df_traj.set_index("day")[["pen_total_weight_kg", "mean_body_weight_kg"]])

        with c2:
            st.markdown("**Daily Nutrient Consumption vs Maintenance Demand**")
            st.line_chart(df_traj.set_index("day")[["me_consumed_mj", "me_maintenance_required_mj"]])

        c3, c4 = st.columns(2)
        with c3:
            st.markdown("**Stored Feed Inventory Reserves (kg Dry Matter)**")
            st.line_chart(df_traj.set_index("day")[["stored_green_kg_dm", "stored_roughage_kg_dm", "stored_concentrate_kg_dm"]])

        with c4:
            st.markdown("**Farm Cash Balance & Cumulative Spoilage (INR / kg)**")
            st.line_chart(df_traj.set_index("day")[["cash_balance", "spoilage_loss_kg_dm"]])

        # Daily Data Table
        with st.expander("🔎 View Full Daily Telemetry Table"):
            st.dataframe(df_traj, use_container_width=True)

with tab_benchmark:
    st.header("Head-to-Head Comparative Benchmark")
    st.markdown(
        "Runs both the **Rule-Based Extension Baseline** and the **Constrained Linear Program (LP)** "
        "across the identical farm profile, weather, and seed for strict experimental fairness."
    )

    if st.button("⚖️ Run Fair Head-to-Head Benchmark"):
        with st.spinner("Running matched simulation trials..."):
            # Trial 1: Rule-based
            sim1 = FarmSimulator(config, pen_profile, resources, active_feed_lib)
            res_rule = sim1.run_simulation(RuleBasedAgronomistPolicy())

            # Trial 2: LP Optimizer
            sim2 = FarmSimulator(config, pen_profile, resources, active_feed_lib)
            res_lp = sim2.run_simulation(LeastCostRationOptimizer(target_adg_g_head=float(target_adg)))

            benchmark_df = compare_simulation_results({
                "Rule-Based Extension Policy": res_rule,
                "Constrained LP Optimizer": res_lp,
            })
            st.dataframe(benchmark_df, use_container_width=True)

            st.session_state["benchmark_results"] = (res_rule, res_lp)

    if "benchmark_results" in st.session_state:
        r_rule, r_lp = st.session_state["benchmark_results"]
        df1 = r_rule.trajectory_df
        df2 = r_lp.trajectory_df

        comp_chart = pd.DataFrame({
            "Day": df1["day"],
            "Rule-Based Weight (kg)": df1["pen_total_weight_kg"],
            "LP Optimizer Weight (kg)": df2["pen_total_weight_kg"],
        }).set_index("Day")

        st.subheader("Comparative Growth Trajectory")
        st.line_chart(comp_chart)

with tab_audit:
    st.header("Scientific Audit Report & Export")
    if "last_sim_result" in st.session_state:
        res = st.session_state["last_sim_result"]
        md_report = generate_summary_markdown(res)

        st.markdown(md_report)

        st.download_button(
            label="📥 Download Daily Trajectory CSV",
            data=res.trajectory_df.to_csv(index=False),
            file_name="foddermind_trajectory_audit.csv",
            mime="text/csv",
        )
        st.download_button(
            label="📄 Download Markdown Audit Report",
            data=md_report,
            file_name="foddermind_scientific_report.md",
            mime="text/markdown",
        )
    else:
        st.info("Execute a simulation run in Tab 2 to generate an exportable scientific audit report.")
